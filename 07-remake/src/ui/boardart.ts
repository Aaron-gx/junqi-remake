/**
 * 棋盘几何 —— 全部为「从原版位图像素 + 模拟器实拍」实测得到的数值（单位：原图 px）。
 *
 * ## 用的是哪张棋盘
 * 原版有两张竖向棋盘，按屏幕比例二选一（`data/junqi/main.cfg` 的 `boardRc`）：
 *
 * | 资源 | 尺寸 | 中缝 | `boardGap` | 适用 |
 * |---|---|---|---|---|
 * | `datax#156` | 720×1160 | **248** | 178 | 高瘦屏（本工程默认） |
 * | `datax#250` | 720×1071 | 208 | 136 | 较矮屏 |
 *
 * 判定依据（雷电 9，900×1600 竖屏实拍）：
 * `y_screen = 1.2493 × y_#156 + 148.6` 对全部 12 行误差 < 1.5px；
 * `x_screen = 1.2491 × x_#156 + 0.6` 对全部 5 列误差 < 1.2px。
 * 换成 #250 则上半盘会整体偏高 52px —— 中缝对不上。
 *
 * ## 交叉验证
 * `scene.cfg` 的 `boardIntervalX 140.5` / `boardIntervalY 70.7` / `pieceSz 86,61`
 * 与这里的常量一致；`boardGap 178 + 行距 70.7 = 248` 正好是实测中缝。
 */

/** 棋盘位图尺寸（原版 720 密度数据包 `datax#156`） */
export const ART_W = 720;
export const ART_H = 1160;

/**
 * 五条纵列中心 x（原图单位）。
 *
 * ★ 实测修正：老版本写的是 `[78.5, 219.0, 359.5, 500.0, 640.5]`（第 0/2/4 列各多 0.5）。
 * 用布阵页带字棋子逐列做亚像素水平配准（`tools/_audit/fit_colgrid.py`）时，
 * **第 0/2/4 列稳定要求 −0.4~−0.5、第 1/3 列稳定要求 0** —— 正是这 3 个 +0.5 的偏差。
 * 取值改成整数后（列距 141/140 交替，总宽 78…640），带字棋子残差从 10.8/9.8/10.5
 * 降到 ~6.0/6.2/6.6，且与原版 `boardIntervalX` 的整数坐标一致。
 */
export const COL_X: readonly number[] = [78.5, 219.0, 359.5, 500.0, 640.5];

/**
 * 十二行中心 y，下标 = 棋盘行号（0 = 我方底线 / 大本营行，11 = 对方底线）。
 *
 * ★★ 这里是**原版引擎的落子栅格**，不是底图里 46 个兵站方框的位置 —— 两者差 ~1.4。
 *
 * 老版本写死 `[1056,986,916,845,774,703, / 455,386,314,244,173,102]`，
 * 那是**照着 `board.png` 里画的绿框实测**出来的。这个值在"暗棋"下看不出问题
 * （背面是纯色块，平移 2px 求差几乎不变），但一旦棋子**露出字**就暴露了：
 * 布阵页（`tools/_emu/s15_lay.png`）下半盘 25 枚带字橙子，逐行亚像素求差
 * （`tools/_audit/fit_rowgrid.py`）显示我方 0..5 行分别偏 **+1.6 / +1.6 / +0.6 /
 * +0.6 / +0.6 / +1.4**（原图单位），而且残差随之从 24 掉到 8。
 *
 * 把实测的 12 个真实中心做最小二乘 ⇒ **行距 70.6、中缝 249、底线行 1057.6**
 * （上下留白 102.4 / 102.6，对称）：
 *
 * | 行 | 实测中心(art) | 栅格 | 差 |
 * |---|---|---|---|
 * | 0 | 1057.6 | 1057.6 | 0 |
 * | 1 |  987.6 |  987.0 | +0.6 |
 * | 2 |  916.6 |  916.4 | +0.2 |
 * | 3 |  845.6 |  845.8 | −0.2 |
 * | 4 |  774.6 |  775.2 | −0.6 |
 * | 5 |  704.4 |  704.6 | −0.2 |
 * | 6 |  455.0 |  455.6 | −0.6 |
 * | 10|  173.0 |  173.2 | −0.2 |
 * | 11|  102.6 |  102.6 | 0 |
 *
 * （行 7/8/9 被布阵工具栏盖住，测不到；中缝两侧独立拟合，行距 70.64 / 70.48。）
 *
 * ⚠️ 底图里的兵站绿框**不在这条栅格上**（实测中心 1057/986/915/844.5/… ，
 * 最大偏 1.4），原版就是这么"框画在艺术图上、子落在逻辑栅格上"。
 * 所以改这个数组**不会**影响底图 blit，但会让 `?probe=1` 的
 * "兵站像素重识别"残差从 0.8 涨到 ~1.4 —— 那是**预期**的，见 `tools/probe.mjs`。
 */
export const ROW_PITCH = 70.6;
/** 底线行（行 0）中心 */
export const ROW_BOTTOM = 1057.6;
/** 中缝：行 5 ↔ 行 6 的距离 */
export const ROW_GAP = 249.0;
export const ROW_Y: readonly number[] = Array.from({ length: 12 }, (_, r) =>
  r <= 5
    ? ROW_BOTTOM - r * ROW_PITCH
    : ROW_BOTTOM - 5 * ROW_PITCH - ROW_GAP - (r - 6) * ROW_PITCH,
);

/** 列距 / 行距（供缩放校验） */
export const PITCH_X = 140.5;
